import assert from 'node:assert/strict';
import { build } from 'esbuild';
const result = await build({entryPoints:['src/lib/auth/config.ts'],bundle:true,platform:'node',format:'esm',write:false});
const {isClerkConfigured} = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
const key = host => `pk_live_${Buffer.from(`${host}$`).toString('base64')}`;
process.env.NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY = key('https://tempo-rs.vercel.app/__clerk');
process.env.CLERK_SECRET_KEY = 'sk_live_fixture';
process.env.CLERK_FRONTEND_API_URL = 'https://noble-ferret-167.clerk.accounts.dev';
assert.equal(isClerkConfigured(),true,'Issuer configuration must not suppress Clerk UI');
process.env.CLERK_FRONTEND_API_URL = 'https://tempo-rs.vercel.app/__clerk';
assert.equal(isClerkConfigured(),true,'App-origin production proxy must be supported');
process.env.CLERK_SECRET_KEY = 'sk_test_fixture';
assert.equal(isClerkConfigured(),false,'Mixed environments must not pass readiness');
process.env.CLERK_SECRET_KEY = '';
assert.equal(isClerkConfigured(),false,'Missing secret must not pass readiness');
process.env.NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY = 'pk_test_fixture';
process.env.CLERK_SECRET_KEY = 'sk_test_fixture';
assert.equal(isClerkConfigured(),true);
console.log('PASS: production proxy key, independent issuer, matching development keys, mixed environment and missing key checks.');
