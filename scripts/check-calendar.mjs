import assert from "node:assert/strict";
import { build } from "esbuild";
const built = await build({entryPoints:["src/lib/calendar-model.ts"],bundle:true,platform:"node",format:"esm",write:false});
const { calendarWeek, calendarMonthWeeks, calendarTasks } = await import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[0].text).toString("base64")}`);
assert.equal(calendarMonthWeeks("2026-10-31").length,5);
assert.equal(calendarMonthWeeks("2021-02-15").length,4);
assert.equal(calendarMonthWeeks("2026-08-01").length,6);
assert.equal(calendarMonthWeeks("2026-10-31")[0][0],"2026-09-28");
assert.equal(calendarMonthWeeks("2026-10-31").at(-1).at(-1),"2026-11-01");
const now = Date.UTC(2026,9,31,12);
const base = {_id:"task",title:"Task",status:"open",progress:"not_started",workDate:"2026-10-31",timezone:"UTC",schedule:{type:"flexible",dueDate:"2026-10-31"}};
assert.deepEqual(calendarWeek("2027-01-01"),["2026-12-28","2026-12-29","2026-12-30","2026-12-31","2027-01-01","2027-01-02","2027-01-03"]);
assert.equal(calendarWeek("2026-11-01")[0],"2026-10-26");
const overnight = {...base,schedule:{type:"fixed",startAt:Date.UTC(2026,9,31,23),endAt:Date.UTC(2026,10,1,1)}};
assert.equal(calendarTasks([overnight],"2026-10-31","UTC",now).length,1);
assert.equal(calendarTasks([overnight],"2026-11-01","UTC",now).length,0);
assert.equal(calendarTasks([overnight],"2026-11-02","UTC",now).length,0);
const multiDay = {...overnight,schedule:{...overnight.schedule,endAt:Date.UTC(2026,10,2,15)}};
const nextOccurrence = {...overnight,_id:"next-occurrence",schedule:{type:"fixed",startAt:Date.UTC(2026,10,1,23),endAt:Date.UTC(2026,10,2,1)}};
assert.deepEqual(calendarTasks([multiDay,nextOccurrence],"2026-11-01","UTC",now),[nextOccurrence]);
assert.deepEqual(calendarTasks([multiDay,nextOccurrence],"2026-11-02","UTC",now),[]);
assert.equal(calendarTasks([{...overnight,schedule:{...overnight.schedule,endAt:Date.UTC(2026,10,1)}}],"2026-11-01","UTC",now).length,0);
assert.equal(calendarTasks([base],"2026-10-31","UTC",now).length,1);
assert.equal(calendarTasks([{...base,schedule:{type:"flexible",dueDate:"2026-11-03"}}],"2026-10-31","UTC",now).length,0);
const carried = {...base,workDate:"2026-10-29",schedule:{type:"flexible",dueDate:"2026-10-29"}};
assert.equal(calendarTasks([carried],"2026-10-31","UTC",now).length,1);
assert.equal(calendarTasks([carried],"2026-11-01","UTC",now).length,0);
const complete = {...carried,status:"completed",completedAt:Date.UTC(2026,9,30,18)};
assert.equal(calendarTasks([complete],"2026-10-31","UTC",now).length,0);
assert.equal(calendarTasks([complete],"2026-10-30","UTC",now).length,1);
const dst = {...base,schedule:{type:"fixed",startAt:Date.UTC(2026,10,1,5,30),endAt:Date.UTC(2026,10,1,7,30)}};
assert.equal(calendarTasks([dst],"2026-11-01","America/New_York",now).length,1);
assert.equal(calendarTasks([dst],"2026-10-31","America/New_York",now).length,0);
assert.equal(calendarTasks([base,overnight],"2026-10-31","UTC",now)[0],overnight);
console.log("PASS: calendar week/year boundaries, fixed blocks crossing midnight, exact midnight end, due dates, carried work, historical completion, DST, and task ordering.");
